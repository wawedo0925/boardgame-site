const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const mod={exports:{}};
new Function('exports','require','module',ts.transpileModule(fs.readFileSync('lib/events/default-groups.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(mod.exports,require,mod);
const {withDefaultGroups}=mod.exports;
let n=0; const id=()=>`draft-${++n}`;
const members=['우영','아라','병준'].map((name,i)=>({user_id:String(i),attendance_status:'PRESENT',profile:{activity_name:name}}));
const group=(name,userIds=[])=>({id:name,name,userIds,sessionId:null,ruleMasterUserId:null});
const initial=withDefaultGroups([],members,id);
assert.equal(initial.length,4); assert.deepEqual(initial.slice(0,3).map(g=>g.userIds),[['0'],['1'],['2']]);
const party={...group('대현 조',['4']),ruleMasterUserId:'4'};
const merged=withDefaultGroups([party],members,id);
assert.equal(merged.length,4);assert.deepEqual(merged[3],party);
assert.equal(withDefaultGroups(merged,members,id).length,4);
const existing=group('우영조',['0','1']);
const partial=withDefaultGroups([existing],members,id);
assert.equal(partial.length,3);assert.deepEqual(partial.find(g=>g.name==='아라 조').userIds,[]);
assert.deepEqual(partial.find(g=>g.id===existing.id),existing);
const absent=withDefaultGroups([],members.map(m=>({...m,attendance_status:'ABSENT'})),id);
assert(absent.every(g=>g.userIds.length===0));
console.log('PASS: empty/GM-only/partial groups, no duplicates or reassignment, absent members excluded');
