const assert = require('node:assert/strict'), fs = require('node:fs');
const { PGlite } = require(process.env.PGLITE_MODULE || '@electric-sql/pglite');
(async () => {
  const db = new PGlite();
  const [a,b,g,h,s,r,old,gm,next] = Array.from({length:9},(_,i)=>`00000000-0000-0000-0000-${String(i+1).padStart(12,'0')}`);
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql as $$select null::uuid$$;
    create table games(id uuid primary key,name text); create table profiles(id uuid primary key,activity_name text);
    create table event_game_sessions(id uuid primary key,game_id uuid);
    create table event_game_rounds(id uuid primary key,session_id uuid);
    create table event_round_players(round_id uuid,user_id uuid,is_gm boolean default false,score numeric,rank integer,is_winner boolean,primary key(round_id,user_id));
    insert into auth.users values('${a}'),('${b}'); insert into games values('${g}','가'),('${h}','나');
    insert into event_game_sessions values('${s}','${g}');
    insert into event_game_rounds values('${r}','${s}'),('${old}','${s}'),('${gm}','${s}'),('${next}','${s}');
    insert into event_round_players(round_id,user_id,score) values('${old}','${a}',10);`);
  await db.exec(fs.readFileSync('supabase/migrations/20260918010000_boardgame_learning_interests.sql','utf8'));
  const register = () => db.exec(`insert into boardgame_learning_interests(game_id,user_id) values('${g}','${a}')`);
  await register();
  await db.exec(`insert into boardgame_learning_interests(game_id,user_id) values('${g}','${b}'),('${h}','${a}')`);
  await db.exec(fs.readFileSync('supabase/migrations/20260918020000_learning_interest_completion.sql','utf8'));
  const count = async () => Number((await db.query(`select count(*) as n from boardgame_learning_interests where game_id='${g}' and user_id='${a}'`)).rows[0].n);
  assert.equal(await count(),1,'migration preserves current registrations');
  await db.exec(`update event_round_players set score=20 where round_id='${old}'`);
  assert.equal(await count(),1,'historical edit preserves registration');
  await db.exec(`insert into event_round_players(round_id,user_id) values('${r}','${a}')`);
  assert.equal(await count(),1,'adding a round is not completion');
  await db.exec(`insert into event_round_players(round_id,user_id,is_gm) values('${gm}','${a}',true)`);
  assert.equal(await count(),1,'GM does not count as playing');
  await db.exec(`update event_round_players set score=0 where round_id='${r}'`);
  assert.equal(await count(),0,'zero score completes play');
  assert.equal(Number((await db.query('select count(*) as n from boardgame_learning_interests')).rows[0].n),2,'other members and games unchanged');
  await register();
  await db.exec(`update event_round_players set score=30 where round_id='${r}';
    update event_round_players set score=null where round_id='${r}';
    update event_round_players set rank=2 where round_id='${r}'`);
  assert.equal(await count(),1,'editing/clearing/restoring same result preserves re-registration');
  await db.exec(`insert into event_round_players(round_id,user_id,is_winner) values('${next}','${a}',false)`);
  assert.equal(await count(),0,'new play loss also completes learning');
  await register();
  await db.exec(`update event_round_players set is_gm=false,rank=3 where round_id='${gm}'`);
  assert.equal(await count(),0,'rank-only player result completes learning');
  await register();
  assert.equal(await count(),1,'no played-history registration restriction');
  console.log('PASS: completion only, old history/edit protection, repeat registration, score/rank/loss, GM exclusion, member/game isolation');
  await db.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
