const assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(require('fs').readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,f);
const {beginNight,propose,approveEffects}=require('../lib/clocktower/night.ts');
const members=['독살범','첩자','세탁부','군인','임프','점쟁이','집사'].map((r,i)=>({user_id:String(i),seat:i+1,name:`P${i}`,birth_year:'1990',alive:true,actual_role:r,shown_role:r}));
let e=beginNight(undefined,1,members);
assert.deepEqual([...new Set(e.tasks.map(t=>t.role))],['하수인 정보','악마 정보','독살범','첩자','세탁부','점쟁이','집사']);
const task=e.tasks.find(t=>t.role==='독살범');
let p=propose(task,['5'],e,members);
e=approveEffects(task,['5'],e,members,{...p,result:'직접 수정한 전달 내용'}).state;
const saved=e.timeline[task.key];
assert.equal(saved.actor,'독살범(P0)');assert.deepEqual(saved.targets,['P5(점쟁이)']);
assert.equal(saved.result,'직접 수정한 전달 내용');assert.equal(e.poison.target,'5');
members[5].actual_role='임프';
e=beginNight(JSON.parse(JSON.stringify(e)),2,members);
assert.deepEqual(e.timeline[task.key],saved);
assert.ok(!e.tasks.some(t=>t.role==='세탁부'));
assert.ok(!JSON.stringify(saved).includes('1990'));
const spy=e.tasks.find(t=>t.role==='첩자');
e=approveEffects(spy,[],e,members,propose(spy,[],e,members)).state;
assert.equal(e.timeline[spy.key].result,'마도서 정보를 전달했습니다.');
console.log('PASS: timeline snapshots and effects');
